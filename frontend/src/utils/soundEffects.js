/**
 * Universal Trophy Sound Dispatcher
 */
export function playAchievementSound(style = 'playstation') {
  if (style === 'xbox') {
    playXboxAchievementSound();
  } else if (style === 'arcade') {
    playArcadeAchievementSound();
  } else {
    playPlayStationTrophySound();
  }
}
